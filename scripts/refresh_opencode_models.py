"""Rewrite src/clara/llm/opencode_models.py: what is known of each OpenCode model without asking it.

    python scripts/refresh_opencode_models.py            read https://models.dev/api.json
    python scripts/refresh_opencode_models.py FILE.json  read a copy of it

OpenCode's own list (`/v1/models`) names the models and nothing else. models.dev says, for each, the API it speaks
(`npm`: the SDK OpenCode uses to reach it), whether it reads pictures and whether it calls tools. Clara uses OpenCode Go
only, so the table holds the models of models.dev's `opencode-go`. (Zen's entries are left out on purpose: the same name
can speak another API there than at Go, as `minimax-m2.7` does.)

Run it when OpenCode adds models, then read the diff: a model missing from the table is shown as unknown, not hidden.
"""

from __future__ import annotations

import json
import sys
from datetime import UTC, datetime
from pathlib import Path

import httpx

SOURCE = "https://models.dev/api.json"
TARGET = Path(__file__).resolve().parent.parent / "src" / "clara" / "llm" / "opencode_models.py"
PROTOCOLS = {
    "@ai-sdk/openai-compatible": "chat",
    "@ai-sdk/openai": "responses",
    "@ai-sdk/anthropic": "messages",
    "@ai-sdk/google": "google",
}


def protocol(provider: dict, model: dict) -> str:
    npm = (model.get("provider") or {}).get("npm") or provider.get("npm") or ""
    return PROTOCOLS.get(npm, npm.removeprefix("@ai-sdk/") or "unknown")


def entry(provider: dict, model: dict) -> tuple[str, bool, bool, bool]:
    return (
        protocol(provider, model),
        "image" in ((model.get("modalities") or {}).get("input") or []),
        bool(model.get("tool_call")),
        bool(model.get("reasoning")),
    )


def table(api: dict) -> dict[str, tuple[str, bool, bool, bool]]:
    go = api["opencode-go"]
    return dict(sorted((name, entry(go, model)) for name, model in go["models"].items()))


def render(found: dict[str, tuple[str, bool, bool, bool]]) -> str:
    lines = [
        f'''"""Generated by scripts/refresh_opencode_models.py from {SOURCE} on {datetime.now(UTC):%Y-%m-%d}: do not edit.

`name: (protocol, pictures, tools, thinking)`. The protocol is the API the model speaks at OpenCode ("chat" is Chat
Completions, the only one Clara speaks); the rest is what models.dev says the model can do.
"""

from __future__ import annotations

MODELS: dict[str, tuple[str, bool, bool, bool]] = {{''',
    ]
    lines += [f"    {json.dumps(name)}: ({json.dumps(kind)}, {pictures}, {tools}, {thinking}),"
              for name, (kind, pictures, tools, thinking) in found.items()]
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if argv:
        api = json.loads(Path(argv[0]).read_text(encoding="utf-8"))
    else:
        response = httpx.get(SOURCE, timeout=60, follow_redirects=True)
        response.raise_for_status()
        api = response.json()
    found = table(api)
    TARGET.write_text(render(found), encoding="utf-8")
    speaking = sum(1 for kind, *_ in found.values() if kind == "chat")
    print(f"{TARGET.relative_to(TARGET.parents[3])}: {len(found)} models, {speaking} that Clara can speak to")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
